import numpy as np
print("\n Creating a 2-D Array")
arr_2d=np.array([[1,2,3],[4,5,6]])
print("\n First Array:\n",arr_2d)
arr_2d1=np.array([[10,20,30],[8,5,7]])
print("\n Second Array:\n",arr_2d1)
print("\n2D array:")
print("Shape:",arr_2d.shape)
print("Dimensions:",arr_2d.ndim)
print("\nIndexing and Slicing")
print("First row of 2D Array:",arr_2d[1])
print("Second column of 2D array:",arr_2d[:,2])
print("\nArray after Addition:\n ",arr_2d+arr_2d1)
print("Array after Subtraction:\n",arr_2d-arr_2d1)
print("\nArray after multiplication:\n",arr_2d*arr_2d1)
